/**
 * Generates the complete 1,080-SKU Searchable Hardware Catalog across all 15 Brands,
 * 12 Hardware Families, and 6 Architectural Finishes.
 */
export function getFullHardwareCatalog() {
  const catalog = [];
  let skuCounter = 1001;

  HARDWARE_BRANDS.forEach((brand) => {
    HARDWARE_FAMILIES.forEach((fam, fIdx) => {
      HARDWARE_FINISHES.forEach((fin) => {
        const seriesPrefix = fam.baseSeries[fIdx % fam.baseSeries.length].split("-")[1] || "GLZ";
        const modelCode = `${brand.id.toUpperCase().slice(0, 3)}-${seriesPrefix}-${skuCounter}`;
        catalog.push({
          sku: modelCode,
          brandId: brand.id,
          brandName: brand.name,
          familyId: fam.familyId,
          familyTitle: fam.title,
          mountingMode: fam.mountingMode,
          cutoutType: fam.cutoutType,
          holeDiaMm: fam.holeDiaMm,
          counterboreDiaMm: fam.counterboreDiaMm || 0,
          notchWidthMm: fam.notchWidthMm || 0,
          notchHeightMm: fam.notchHeightMm || 0,
          edgeDistX: fam.edgeDistX,
          edgeDistY: fam.edgeDistY,
          finishId: fin.id,
          finishName: fin.name,
          colorHex: fin.colorHex,
          specSummary: fam.specSummary
        });
        skuCounter++;
      });
    });
  });

  return catalog; // 15 Brands × 12 Families × 6 Finishes = 1,080 Complete Hardware SKUs!
}
